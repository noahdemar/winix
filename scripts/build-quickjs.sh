#!/bin/bash
# Cross-build QuickJS (qjs only) for the guest into the overlay staging dir. Called by build.sh (needs its env).
# Needs: LW_WORKSPACE LW_VARIANT BUILD_ROOT SRC (extracted linux-wasm tree) REPO OVERLAY
set -euo pipefail

QJS_VERSION=2026-06-04
QJS_SHA256=b376e839b322978313d929fd20663b11ba58b75df5a46c126dd19ea2fa70ad2a
QJS_URL=https://bellard.org/quickjs/quickjs-$QJS_VERSION.tar.xz

I="$LW_WORKSPACE/install"
Q="$BUILD_ROOT/quickjs"
TARBALL="$BUILD_ROOT/dl/quickjs-$QJS_VERSION.tar.xz"
mkdir -p "$BUILD_ROOT/dl"
if [ ! -f "$TARBALL" ]; then curl -fsSL -o "$TARBALL" "$QJS_URL"; fi
echo "$QJS_SHA256  $TARBALL" | sha256sum -c - >/dev/null

rm -rf "$Q" && mkdir -p "$Q/src" "$Q/obj"
tar -xJf "$TARBALL" -C "$Q/src" --strip-components=1
for p in "$REPO"/patches/quickjs/*.patch; do
  [ -f "$p" ] && patch -p1 -d "$Q/src" < "$p" >/dev/null
done
cd "$Q/src"

DEFS=(-D_GNU_SOURCE "-DCONFIG_VERSION=\"$QJS_VERSION\"")
# repl.c is generated by qjsc, which has to run on the host
gcc -O2 "${DEFS[@]}" -DCONFIG_CC=\"gcc\" -DCONFIG_PREFIX=\"/usr/local\" -fwrapv \
  qjsc.c quickjs.c dtoa.c libregexp.c libunicode.c cutils.c quickjs-libc.c -lm -ldl -lpthread -o "$Q/qjsc"
"$Q/qjsc" -s -c -o repl.c -m repl.js

# Same toolchain and flags as upstream's BusyBox userland (see linux-wasm.sh)
export REAL_LLVM="$I/llvm/bin"
CC="$SRC/tools/fake-llvm/clang"
CFLAGS=(--target=wasm-linux-musl -march="${LW_VARIANT%%_*}" "--sysroot=$I/musl-$LW_VARIANT" -fPIC -D__linux__
  --rtlib=compiler-rt -O2 -fwrapv -funsigned-char "${DEFS[@]}")
objs=()
for f in qjs repl quickjs dtoa libregexp libunicode cutils quickjs-libc; do
  "$CC" "${CFLAGS[@]}" -c "$f.c" -o "$Q/obj/$f.o" 2>>"$Q/build.log"
  objs+=("$Q/obj/$f.o")
done
"$CC" "${CFLAGS[@]}" "-m${LW_VARIANT%%_*}" -shared "${objs[@]}" -o "$Q/qjs" -lm -lpthread 2>>"$Q/build.log"

mkdir -p "$OVERLAY/usr/bin"
install -m 755 "$Q/qjs" "$OVERLAY/usr/bin/qjs"
ls -l "$OVERLAY/usr/bin/qjs"
